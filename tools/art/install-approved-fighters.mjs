import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../../', import.meta.url);
const publicRoot = new URL('apps/game/public/assets/', root);
const backup = new URL('art/fighters/installed-before-three-character-roster/', root);
mkdirSync(backup, { recursive: true });
const selected = [
  ['taiko', 'taiko-v2', 'fighter-p1'],
  ['riot', 'riot-v2-first', 'fighter-p2'],
  ['anchor', 'anchor-v3', 'fighter-anchor'],
];
const geometry = {};
for (const [id, source, texture] of selected) {
  for (const ext of ['png', 'json']) {
    const target = new URL(`${id}.${ext}`, publicRoot);
    const saved = new URL(`${id}.${ext}`, backup);
    if (existsSync(target) && !existsSync(saved)) copyFileSync(target, saved);
    copyFileSync(new URL(`experiments/${source}.${ext}`, publicRoot), target);
  }
  const path = new URL(`${id}.json`, publicRoot);
  const atlas = JSON.parse(readFileSync(path));
  atlas.meta.image = `${id}.png`;
  writeFileSync(path, JSON.stringify(atlas, null, 2) + '\n');
  const alignment = JSON.parse(
    readFileSync(new URL(`art/fighters/${source}/native-192/alignment.json`, root)),
  );
  geometry[texture] = {
    originX: 80,
    originY: 156,
    shadowWidth: id === 'anchor' ? 48 : 40,
    kickOffset: 30,
    bounds: Object.fromEntries(
      alignment.audit.map(({ name, placed }) => [name, { left: placed.left, width: placed.width }]),
    ),
  };
}
writeFileSync(
  new URL('apps/game/src/config/fighterGeometry.ts', root),
  '// Generated by tools/art/install-approved-fighters.mjs from approved native placement audits.\n' +
    'export const FIGHTER_GEOMETRY: Record<string, {originX:number;originY:number;shadowWidth:number;kickOffset:number;bounds:Record<string,{left:number;width:number}>}> = ' +
    JSON.stringify(geometry, null, 2) +
    ';\n',
);
console.log('Installed Taiko v2, Riot v2-first and Anchor v3; previous production art preserved.');
